--[[----------------------------------------------------------------------------
    XPLedger - Pet sprite
    Animated murloc drawn from the sprite sheets in Media\Pet\Murloc<stage>.tga
    (4 columns x 32 rows of 32px cells), generated by tools/pet/build-murloc.js.
    The rows of ANIMATIONS must match that script.

    Animation fields:
      row        sheet row (0-based)
      fps        frames per second
      sequence   columns to show (1-based), in order
      loopFrom   step the sequence restarts from (default 1), so an animation
                 can play an intro once and then loop its last frames
------------------------------------------------------------------------------]]

local _, ns = ...

local PetSprite = {}
ns.PetSprite = PetSprite

PetSprite.SIZE = 32
PetSprite.COLUMNS = 4
PetSprite.ROWS = 32
PetSprite.TEXTURE_PATH = "Interface\\AddOns\\" .. ns.name .. "\\Media\\Pet\\Murloc"

PetSprite.ANIMATIONS = {
    idle = { row = 0, fps = 3, sequence = { 1, 2, 1, 2, 1, 2, 1, 3, 1, 2, 1, 2, 4, 4, 2 } },
    happy = { row = 1, fps = 8, sequence = { 1, 2, 3, 4 } },
    party = { row = 2, fps = 6, sequence = { 1, 2, 3, 4 } },
    fight = { row = 3, fps = 6, sequence = { 1, 2, 1, 2, 3, 4 } },
    swim = { row = 4, fps = 4, sequence = { 1, 2, 3, 4 } },
    sleep = { row = 5, fps = 1.2, sequence = { 1, 2, 3, 4 } },
    victory = { row = 6, fps = 7, sequence = { 1, 2, 3, 4 } },
    relief = { row = 7, fps = 3, sequence = { 1, 2, 1, 2, 3, 3, 4, 4 }, loopFrom = 7 },
    dead = { row = 8, fps = 2.5, sequence = { 1, 2, 3, 3, 3, 4, 3, 3, 3, 3, 4 }, loopFrom = 3 },
    ghost = { row = 9, fps = 4, sequence = { 1, 2, 3, 4 } },
    revive = { row = 10, fps = 5, sequence = { 1, 2, 3, 4 } },
