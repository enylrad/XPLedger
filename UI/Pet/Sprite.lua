    -- Crushed into a ball of Void on the way into the rage form (and out).
    collapse = { row = 26, fps = 6, sequence = { 1, 2, 3, 4 }, loopFrom = 4 },
}
local ANIMATIONS = PetSprite.ANIMATIONS

local Sprite = {}
Sprite.__index = Sprite

local function CreateSheetTexture(parent, sublevel)
    local texture = parent:CreateTexture(nil, "ARTWORK", nil, sublevel)
    -- Keep the pixels crisp at any scale.
    if texture.SetSnapToPixelGrid then
        texture:SetSnapToPixelGrid(false)
        texture:SetTexelSnappingBias(0)
    end
    return texture
end

--- Creates an animated companion filling `parent`.
function PetSprite.Create(parent)
    local sprite = setmetatable({ parent = parent, elapsed = 0, step = 1, scale = 1, x = 0, y = 0 }, Sprite)
    sprite.texture = CreateSheetTexture(parent, 0)
    -- Additive copy of the frame, used to make the companion glow.
    sprite.glow = CreateSheetTexture(parent, 1)
    sprite.glow:SetBlendMode("ADD")
    sprite.glow:SetAlpha(0)
    sprite:SetOffset(0, 0)
    sprite:SetSpecies("murloc")
    sprite:SetAnimation("idle")
    return sprite
end

--- Path of a species' sheet (unknown species fall back to the murloc).
function PetSprite.GetTexture(species)
    return PetSprite.TEXTURE_DIR .. (PetSprite.SHEETS[species] or PetSprite.SHEETS.murloc)
end

function Sprite:SetSpecies(species)
    if not PetSprite.SHEETS[species] then
        species = "murloc"
    end
    if self.species == species then
        return
    end
    self.species = species
    for _, texture in ipairs({ self.texture, self.glow }) do
        texture:SetTexture(PetSprite.GetTexture(species), nil, nil, "NEAREST")
    end
    self:ShowFrame()
end

--- Switches animation. `restart` replays it even when it is already showing.
function Sprite:SetAnimation(name, restart)
    if self.animationName == name and not restart then
        return
    end
    self.animationName = name
    self.animation = ANIMATIONS[name] or ANIMATIONS.idle
    self.step, self.elapsed = 1, 0
    self:ShowFrame()
end

function Sprite:ShowFrame()
    local animation = self.animation
    if not animation then
        return
    end
    local cells = animation.cells or 1
    local frame = animation.sequence[self.step] - 1
    local perRow = PetSprite.COLUMNS / cells
    local column = (frame % perRow) * cells
    local row = animation.row + math.floor(frame / perRow) * cells
    local left, right = column / PetSprite.COLUMNS, (column + cells) / PetSprite.COLUMNS
    local top, bottom = row / PetSprite.ROWS, (row + cells) / PetSprite.ROWS
    self.texture:SetTexCoord(left, right, top, bottom)
    self.glow:SetTexCoord(left, right, top, bottom)
end

function Sprite:Update(elapsed)
    local animation = self.animation
    local duration = 1 / animation.fps
    self.elapsed = self.elapsed + elapsed
    if self.elapsed >= duration then
        -- A long hitch skips frames instead of fast-forwarding through them.
        self.elapsed = self.elapsed % duration
        self.step = self.step + 1
        if self.step > #animation.sequence then
            self.step = animation.loopFrom or 1
        end
        self:ShowFrame()
    end
end

--- Tints the murloc (the ghost); no arguments restores the normal colors.
function Sprite:SetTint(r, g, b, alpha)
    self.texture:SetVertexColor(r or 1, g or 1, b or 1)
    self.texture:SetAlpha(alpha or 1)
end

--- Moves the drawing inside its frame (jumps, floating), in screen pixels.
function Sprite:SetOffset(x, y)
    self.x, self.y = x, y
    self:Anchor()
end

--- Size of the drawing compared with its frame. Above 1 it grows from the
--- bottom centre and spills out of the frame (the rage form).
function Sprite:SetScale(scale)
    self.scale = scale or 1
    self:Anchor()
end

function Sprite:Anchor()
    local x, y, scale = self.x, self.y, self.scale
    for _, texture in ipairs({ self.texture, self.glow }) do
        texture:ClearAllPoints()
        if scale == 1 then
            texture:SetPoint("TOPLEFT", self.parent, "TOPLEFT", x, y)
            texture:SetPoint("BOTTOMRIGHT", self.parent, "BOTTOMRIGHT", x, y)
        else
            local width, height = self.parent:GetSize()
            texture:SetPoint("BOTTOM", self.parent, "BOTTOM", x, y)
            texture:SetSize(width * scale, height * scale)
        end
    end
end
