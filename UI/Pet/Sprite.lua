--[[----------------------------------------------------------------------------
    XPLedger - Pet sprite
    Animated companion drawn from the sprite sheets in Media\Pet\<Species>.tga
    (4 columns x 32 rows of 32px cells), generated by tools/pet/build-pets.js.
    Every species uses the same rows, which must match that script.

    Animation fields:
      row        sheet row (0-based)
      fps        frames per second
      sequence   columns to show (1-based), in order
      loopFrom   step the sequence restarts from (default 1), so an animation
                 can play an intro once and then loop its last frames
      cells      cells per side of every frame (default 1). The rage form uses
                 2: 64x64 frames, two per pair of rows from `row` on, shown
                 at twice the size of the pet (see Sprite:SetScale)
------------------------------------------------------------------------------]]

local _, ns = ...

local PetSprite = {}
ns.PetSprite = PetSprite

PetSprite.SIZE = 32
PetSprite.COLUMNS = 4
PetSprite.ROWS = 32
PetSprite.TEXTURE_DIR = "Interface\\AddOns\\" .. ns.name .. "\\Media\\Pet\\"

-- Every species and the sheet it is drawn from, in the order of the options.
-- A new species also needs its own phrases, written for its personality, in
-- every locale: see "Adding a new pet" in UI\Pet\Talk.lua.
PetSprite.SPECIES = { "murloc", "void" }
PetSprite.SHEETS = {
    murloc = "Murloc",
    void = "Void",
}

-- Species with a rage form (the `rage` and `collapse` animations, drawn only
-- on their sheet): they turn into it for a few seconds when they are clicked
-- too much.
PetSprite.RAGE_FORMS = {
    void = true,
}

PetSprite.ANIMATIONS = {
    idle = { row = 0, fps = 3, sequence = { 1, 2, 1, 2, 1, 2, 1, 3, 1, 2, 1, 2, 4, 4, 2 } },
